"""
GNN 渗流预测入门示例（标准 PyTorch Geometric 流程）。

====================================================================
这个示例要解决的问题
====================================================================
给定一个网络，以及一次随机节点攻击（每个节点以概率 q 失效），
预测每个【幸存节点】是否仍属于【巨连通分量 (giant connected component)】。

- 巨连通分量：攻击后剩余子图中最大的连通分支（规模随 N 增大而发散时称巨分量）
- 标签：由 BFS 求出最大连通分支，节点在其中记 1，否则记 0
- 任务类型：节点级二分类

为什么这个问题重要（背景）：
- 它是网络渗流 / 网络鲁棒性的核心问题。攻击强度 q 超过临界值 q_c 时，
  巨分量解体、网络随之崩溃；经典理论用生成函数给出巨分量比例 S(q)。
- 但经典解析结果依赖 ER / 配置模型等理想假设。本示例改用 GNN 做
  【数据驱动】预测：直接从真实网络拓扑 + 攻击后的存活状态，逐节点判断
  是否还在巨分量中，可推广到任意真实网络结构。
- 对应 paper_1 的渗流理论，是「GNN 介入网络科学」的入门示例。

为什么适合 GNN：
- “是否在巨分量中”取决于【多跳连通性】——能否通过幸存节点连到一个巨大的
  连通簇。这正是消息传递（message passing）天然能刻画的结构信息；
  普通 MLP 只看节点自身特征，无法判断连通性。

====================================================================
本示例的具体设定
====================================================================
- 底图：真实引文网络 Cora（2708 节点，7 个主题社团）
- 攻击：随机移除 q=0.55 的节点（近临界，巨分量/幸存者 ≈ 0.49，类别平衡）
- 输入：x = [归一化度+噪声, 存活标志, 0]，edge_index = 拓扑
- 模型：3 层 GCNConv（torch_geometric.nn.GCNConv）
- 训练：标准节点分类循环（Adam + 交叉熵），按验证集选最佳模型

文件结构：
- gen_data.py   读 Cora 拓扑 + 跑渗流 + 算标签 → 返回 PyG Data（含 train/val/test mask）
- model.py      3 层 GCNConv
- train.py      标准 PyG 训练循环，保存 tiny_gcn.pt
- infer.py      加载权重评估

运行：
    python train.py
    python infer.py

数据：Cora 只用到 gnn_percolation/data/Cora/raw/ind.cora.graph（拓扑）。

结果（seed=42）：
- 验证Acc 随 epoch 从 ~0.42 升到 ~0.67，呈现学习曲线
- 测试 Acc≈0.69，显著超过多数类基线 0.51
- 预测的巨分量比例 S 与真值接近
"""
